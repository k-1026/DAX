export type SettingRow = { key: string; value: unknown; description: string | null };

export function describeSetting(row: SettingRow): { group: SettingGroup; label: string; text: string; note?: string; rawDescription: string } {
  const description = row.description ?? row.key;
  const item = SETTING_LABELS[description];
  if (!item) {
    return { group: "기타", label: description, text: row.value === null ? "제한 없음" : String(row.value), rawDescription: description };
  }
  const text =
    row.value === null
      ? (item.nullText ?? "제한 없음")
      : item.show
        ? item.show(row.value)
        : `${row.value}${item.unit ? (/^[%]/.test(item.unit) ? "" : " ") + item.unit : ""}`.replace(/(\d) %/, "$1%");
  return { group: item.group, label: item.label, text, note: item.note, rawDescription: description };
}
